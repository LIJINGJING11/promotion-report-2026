const formatVideoTime = (seconds) => {
  if (!Number.isFinite(seconds) || seconds < 0) return '00:00';
  const minutes = Math.floor(seconds / 60);
  const remainingSeconds = Math.floor(seconds % 60).toString().padStart(2, '0');
  return `${minutes.toString().padStart(2, '0')}:${remainingSeconds}`;
};

const setupProjectVideoPlayer = () => {
  const player = projectDialogMedia.querySelector('.project-video-player');
  if (!player) return;

  const video = player.querySelector('video');
  const playButton = player.querySelector('[data-video-action="play"]');
  const progress = player.querySelector('[data-video-action="progress"]');
  const time = player.querySelector('[data-video-time]');
  const rateButtons = player.querySelectorAll('[data-video-rate]');

  const syncPlayer = () => {
    const duration = Number.isFinite(video.duration) ? video.duration : 0;
    progress.max = duration;
    progress.value = Math.min(video.currentTime || 0, duration);
    time.textContent = `${formatVideoTime(video.currentTime)} / ${formatVideoTime(duration)}`;
    playButton.textContent = video.paused ? '▶' : 'Ⅱ';
    playButton.setAttribute('aria-label', video.paused ? '播放' : '暂停');
  };

  playButton.addEventListener('click', () => {
    if (video.paused) video.play().catch(() => {});
    else video.pause();
  });
  progress.addEventListener('input', () => {
    video.currentTime = Number(progress.value);
    syncPlayer();
  });
  rateButtons.forEach((button) => {
    button.addEventListener('click', () => {
      video.playbackRate = Number(button.dataset.videoRate);
      rateButtons.forEach((rateButton) => rateButton.classList.toggle('is-active', rateButton === button));
    });
  });
  ['loadedmetadata', 'durationchange', 'timeupdate', 'play', 'pause', 'ended'].forEach((eventName) => {
    video.addEventListener(eventName, syncPlayer);
  });

  syncPlayer();
  video.play().catch(() => {});
};

