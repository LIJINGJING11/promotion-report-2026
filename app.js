const dialog = document.querySelector('#media-dialog');
const dialogMedia = dialog.querySelector('.dialog-media');
const dialogCaption = dialog.querySelector('.dialog-caption');
document.querySelectorAll('[data-media]').forEach(card => {
  card.addEventListener('click', () => {
    const src = card.dataset.src;
    dialogMedia.innerHTML = card.dataset.media === 'video'
      ? `<video src="${src}" controls autoplay playsinline></video>`
      : `<img class="dialog-zoomable" src="${src}" alt="${card.dataset.title}" title="点击继续放大" />`;
    dialogCaption.textContent = card.dataset.media === 'video' ? card.dataset.title : `${card.dataset.title} · 点击图片可继续放大`;
    dialog.showModal();
    dialogMedia.scrollTo({ top: 0, left: 0 });
  });
});
dialogMedia.addEventListener('click', (event) => {
  if (event.target.matches('.dialog-zoomable')) event.target.classList.toggle('is-zoomed');
});
document.querySelector('.dialog-close').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => { if (event.target === dialog) dialog.close(); });

const progressBar = document.querySelector('#progress-bar');
const updateProgress = () => {
  const max = document.documentElement.scrollHeight - window.innerHeight;
  progressBar.style.width = `${max ? (window.scrollY / max) * 100 : 0}%`;
};
window.addEventListener('scroll', updateProgress, { passive: true });
updateProgress();

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => { if (entry.isIntersecting) entry.target.classList.add('is-visible'); });
}, { threshold: .11 });
document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

const navLinks = [...document.querySelectorAll('.top-nav a')];
const sections = navLinks.map(link => document.querySelector(link.getAttribute('href'))).filter(Boolean);
const sectionObserver = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      navLinks.forEach(link => link.style.color = link.getAttribute('href') === `#${entry.target.id}` ? 'var(--orange)' : '');
    }
  });
}, { rootMargin: '-35% 0px -55% 0px', threshold: 0 });
sections.forEach(section => sectionObserver.observe(section));
